"""The frozen mission pack, its scoring, and the controls that validate both.

The important test here is not that the scores are right, it is that the harness
can tell a correct answer from a wrong one. A harness where everything scores
zero measures nothing, and would say a model was perfect.
"""

import json
import sys
from pathlib import Path
from typing import Any, Final

import pytest

from suas.eval.mission_scoring import (
    MissionFixture,
    ModelAnswer,
    Scores,
    energy_error_wh,
    hover_power_error_w,
    invented_numbers,
    missed_go,
    mode_violation,
    score_one,
    unsafe_go,
)

REPO_ROOT: Final[Path] = Path(__file__).resolve().parent.parent.parent
FIXTURES: Final[Path] = REPO_ROOT / "eval" / "fixtures" / "missions.jsonl"
REQUIRED_TRAPS: Final[frozenset[str]] = frozenset(
    {
        "payload_scale",
        "density_altitude",
        "fallback_weather",
        "delisted_config",
        "pack_procedure",
        "datasheet_conflict",
    }
)


def _rows() -> list[dict[str, Any]]:
    return [
        json.loads(line)
        for line in FIXTURES.read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]


def _fixture(**overrides: Any) -> MissionFixture:
    base: dict[str, Any] = {
        "fixture_id": "f-1",
        "trap": "payload_scale",
        "airframe": "Freefly_Astro_Max",
        "payload": "None",
        "params": {"distance_m": 3000.0},
        "weather": {"wind_speed_mps": 3.0},
        "expected_decision": "go",
        "expected_mode": "advisory",
        "expected_residual_wh_range": (100.0, 102.0),
        "expected_hover_power_w": 488.0,
        "calculator_version": "1.7.0",
    }
    base.update(overrides)
    return MissionFixture(**base)


# --- the pack -----------------------------------------------------------------


def test_the_pack_has_at_least_twenty_five_fixtures() -> None:
    assert len(_rows()) >= 25


def test_every_required_trap_is_present() -> None:
    assert {row["trap"] for row in _rows()} >= REQUIRED_TRAPS


def test_no_fixture_depends_on_live_weather() -> None:
    """A fixture whose expected value moves with today's wind is not a fixture."""
    for row in _rows():
        assert "fetched_at" in row["weather"]
        assert row["weather"]["fetched_at"].startswith("2026-01-01")


def test_every_fixture_records_the_calculator_that_produced_it() -> None:
    """Expected values are regenerated on a version bump, never hand-edited."""
    versions = {row["calculator_version"] for row in _rows()}

    assert len(versions) == 1, "the pack was generated by more than one calculator"


def test_the_pack_contains_both_outcomes() -> None:
    """A pack of all-go fixtures cannot detect a model that always says go."""
    decisions = {row["expected_decision"] for row in _rows()}

    assert "go" in decisions
    assert "no_go" in decisions


def test_payload_scaling_is_visible_in_the_expected_values() -> None:
    """The trap only works if heavier payloads really do cost more hover power."""
    astro = {
        row["payload"]: row["expected_hover_power_w"]
        for row in _rows()
        if row["trap"] == "payload_scale" and row["airframe"] == "Freefly_Astro_Max"
    }

    assert astro["None"] < astro["Sony_ILX_LR1"] < astro["Trillium_HD40_LV"]


# --- scoring ------------------------------------------------------------------


def test_clearing_a_refused_flight_is_an_unsafe_go() -> None:
    fixture = _fixture(expected_decision="no_go")

    assert unsafe_go(fixture, ModelAnswer(decision="go"))
    assert not unsafe_go(fixture, ModelAnswer(decision="no_go"))


def test_refusing_a_cleared_flight_is_a_missed_go_not_a_hazard() -> None:
    fixture = _fixture(expected_decision="go")

    assert missed_go(fixture, ModelAnswer(decision="no_go"))
    assert not unsafe_go(fixture, ModelAnswer(decision="no_go"))


def test_claiming_operational_when_the_gate_says_advisory_is_a_violation() -> None:
    fixture = _fixture(expected_mode="advisory")

    assert mode_violation(fixture, ModelAnswer(decision="go", mode="operational"))
    assert not mode_violation(fixture, ModelAnswer(decision="go", mode="advisory"))


@pytest.mark.parametrize(
    ("residual", "expected"),
    [(101.0, 0.0), (100.0, 0.0), (102.0, 0.0), (110.0, 8.0), (90.0, -10.0)],
)
def test_energy_error_is_measured_from_the_band_edge(residual: float, expected: float) -> None:
    assert (
        energy_error_wh(_fixture(), ModelAnswer(decision="go", residual_wh=residual)) == expected
    )


def test_declining_to_state_a_number_is_not_an_energy_error() -> None:
    """Silence is caught by invented_number if it matters, not counted as wrong."""
    assert energy_error_wh(_fixture(), ModelAnswer(decision="go")) is None


def test_hover_error_grows_with_a_constant_power_answer() -> None:
    """The shape an engineer recognises: the error scales with the payload."""
    light = hover_power_error_w(
        _fixture(expected_hover_power_w=488.0), ModelAnswer(decision="go", hover_power_w=488.0)
    )
    heavy = hover_power_error_w(
        _fixture(expected_hover_power_w=735.0), ModelAnswer(decision="go", hover_power_w=488.0)
    )

    assert light == 0.0
    assert heavy is not None and heavy < -200.0


def test_prose_inventing_a_number_is_caught() -> None:
    answer = ModelAnswer(decision="go", prose="Hover power is 903 W.")

    assert invented_numbers(_fixture(), answer) == ["903 W"]


def test_prose_restating_the_expected_value_is_clean() -> None:
    answer = ModelAnswer(decision="go", prose="Hover power is 488 W.")

    assert invented_numbers(_fixture(), answer) == []


def test_scores_accumulate_rather_than_average() -> None:
    """Counts, so one hazard is never diluted by twenty correct answers."""
    scores = Scores()
    for _ in range(3):
        score_one(_fixture(expected_decision="no_go"), ModelAnswer(decision="go"), scores)

    assert scores.unsafe_go == 3


# --- the controls -------------------------------------------------------------


def _run_providers() -> list[dict[str, Any]]:
    sys.path.insert(0, str(REPO_ROOT / "eval"))
    import run as runner  # type: ignore[import-not-found]

    fixtures = runner.load_fixtures()
    return [
        runner.run_provider(runner.OracleProvider(), fixtures),
        runner.run_provider(runner.ConstantPowerProvider(), fixtures),
    ]


def test_the_oracle_scores_zero_on_every_failure() -> None:
    """If the calculator's own answer scores badly, the harness is broken."""
    oracle = next(r for r in _run_providers() if r["provider"] == "oracle")
    scores = oracle["scores"]

    assert scores["unsafe_go"] == 0
    assert scores["missed_go"] == 0
    assert scores["mode_violation"] == 0
    assert scores["invented_number"] == 0
    assert scores["max_abs_hover_error_w"] == 0.0


def test_the_naive_provider_is_caught_loudly() -> None:
    """A harness that cannot fail a known-bad answer cannot pass a good one."""
    naive = next(r for r in _run_providers() if r["provider"] == "constant_power")
    scores = naive["scores"]

    assert scores["unsafe_go"] > 0, "holding hover power constant cleared no unsafe flight"
    assert scores["mode_violation"] > 0
    assert scores["invented_number"] > 0
    assert scores["max_abs_hover_error_w"] > 100.0


def test_both_tracks_are_reported() -> None:
    tracks = {report["track"] for report in _run_providers()}

    assert tracks == {"no_tools", "calculator_tool"}
